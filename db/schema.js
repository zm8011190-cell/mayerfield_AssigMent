import { pgTable, serial, text, integer, boolean, date, timestamp } from "drizzle-orm/pg-core";
import { user } from "./auth-schema.js"; // generated by Better Auth in Assignment 3

export const books = pgTable("books", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  author: text("author").notNull(),
  priceCents: integer("price_cents").notNull(),
  category: text("category").notNull(), // "Fiction" or "Nonfiction"
  staffPick: boolean("staff_pick").notNull().default(false),
  note: text("note").notNull().default(""),
  cover: text("cover").notNull(),
});

export const events = pgTable("events", {
  id: serial("id").primaryKey(),
  eventDate: date("event_date").notNull(),
  title: text("title").notNull(),
  description: text("description").notNull(),
});

// One row per purchase. status moves "pending" -> "paid", and only the
// Stripe webhook is allowed to make that change.
export const orders = pgTable("orders", {
  id: serial("id").primaryKey(),
  userId: text("user_id")
    .notNull()
    .references(() => user.id),
  status: text("status").notNull().default("pending"), // pending | paid | failed
  totalCents: integer("total_cents").notNull(),
  stripeSessionId: text("stripe_session_id").unique(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// What was bought in each order. unitPriceCents is a snapshot of the price
// at purchase time, so later price changes never rewrite old orders.
export const orderItems = pgTable("order_items", {
  id: serial("id").primaryKey(),
  orderId: integer("order_id")
    .notNull()
    .references(() => orders.id, { onDelete: "cascade" }),
  bookId: integer("book_id")
    .notNull()
    .references(() => books.id),
  quantity: integer("quantity").notNull(),
  unitPriceCents: integer("unit_price_cents").notNull(),
});
